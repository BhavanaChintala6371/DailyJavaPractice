package control_flow_if_else_loops;

/**
 * Problem 4: Print numbers from 10 to 1
 * Concept tested: Reverse for loop and decrement operator in Java.
 */

public class PrintNumbersTenToOne {
    public static void main(String[] args) {

        // Print numbers from 10 down to 1
        for (int i = 10; i >= 1; i--) {
            System.out.println("i=" +i);
        }

    }
}